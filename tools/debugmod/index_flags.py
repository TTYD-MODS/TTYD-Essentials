#!/usr/bin/env python3
"""Create a source-reference index for literal global saved-work flag IDs."""
from collections import defaultdict
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
GSWF = re.compile(r'\bGSWF\s*\(\s*(0[xX][\da-fA-F]+|\d+)\s*\)')
DIRECT = re.compile(r'\bsw(?:Get|Set|Clear)\s*\(\s*(0[xX][\da-fA-F]+|\d+)\s*\)')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path, help="LLCOOLT/ttyd source checkout")
    upstream = parser.parse_args().upstream.resolve(strict=True)
    refs = defaultdict(set)
    for directory in ('src', 'rels'):
        for file in (upstream / directory).rglob('*'):
            if file.suffix not in ('.c', '.h', '.cpp'):
                continue
            relative = file.relative_to(upstream).as_posix()
            for lineno, line in enumerate(file.read_text(errors='replace').splitlines(), 1):
                for regex in (GSWF, DIRECT):
                    for match in regex.finditer(line):
                        value = int(match.group(1), 0)
                        if 0 <= value < 8192:
                            refs[value].add((relative, lineno))
    output = [
        '# Global flag source index', '',
        'Generated by `python3 tools/debugmod/index_flags.py /path/to/upstream`. This is a literal-reference index, not a list of verified flag meanings. It includes references in comments and conditional builds; it misses computed flag IDs. An entry does not establish what a flag does. The 8,192-bit flag bank also contains IDs without literal references in this index. See [FLAGS.md](../mods/FLAGS.md) for the smaller set of reviewed meanings.', '',
        f'{len(refs)} distinct flag IDs have literal references in the source scan.', '',
        '| Flag | References |', '| ---: | --- |',
    ]
    for flag, locations in sorted(refs.items()):
        per_file = defaultdict(list)
        for file, line in sorted(locations):
            per_file[file].append(line)
        links = []
        for file, lines in sorted(per_file.items()):
            numbers = ','.join(map(str, lines[:3]))
            if len(lines) > 3:
                numbers += f', +{len(lines)-3}'
            links.append(f'`{file}:{numbers}`')
        output.append(f'| {flag} | ' + '; '.join(links) + ' |')
    target = ROOT / 'docs/FLAG_INDEX.md'
    target.write_text('\n'.join(output) + '\n')
    print(f'Indexed {len(refs)} distinct flags in {target}')


if __name__ == '__main__':
    main()
